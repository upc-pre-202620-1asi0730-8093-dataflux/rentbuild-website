test('accordion, billing selection and accessible dialogs work', async ({ page }) => {
  await page.goto('/')
  const buttons = page.locator('.showcase__item button')
  await buttons.first().click()
  await expect(buttons.first()).toHaveAttribute('aria-expanded', 'true')
  await buttons.nth(1).click()
  await expect(buttons.first()).toHaveAttribute('aria-expanded', 'false')
  await expect(buttons.nth(1)).toHaveAttribute('aria-expanded', 'true')
  await page.locator('.billing-switch button').first().click()
  await openSignup(page)
  await expect(page.locator('.access-dialog__plan')).toContainText('Monthly')
  await expect(page.locator('body')).toHaveClass(/dialog-open/)
  await page.keyboard.press('Escape')
  await expect(page.locator('dialog')).not.toBeVisible()
  await expect(page.locator('.pricing-card .btn').first()).toBeFocused()
  await page.locator('.site-footer__bottom button').first().click()
  await expect(page.locator('dialog')).toBeVisible()
  await expect(page.locator('dialog form')).toHaveCount(0)
})

