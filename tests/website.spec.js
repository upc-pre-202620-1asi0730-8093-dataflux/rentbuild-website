test('mobile navigation closes on Escape and on selecting a section', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  const toggle = page.locator('.navbar__toggle')
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-expanded', 'true')
  await page.keyboard.press('Escape')
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(toggle).toBeFocused()
  await toggle.click()
  await page.locator('.navbar__links a').last().click()
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})

test('configured contact, newsletter and authentication send JSON and handle failures', async ({ page }) => {
  const requests = []
  await page.route('**/test-api/*', async route => {
    requests.push({ url: route.request().url(), body: route.request().postDataJSON() })
    await route.fulfill({ status: route.request().url().endsWith('/login') ? 401 : 200, contentType: 'application/json', body: '{}' })
  })
  await page.goto('http://127.0.0.1:4182')
  await expect(page.locator('.contact__email')).toHaveAttribute('href', 'mailto:contact@example.com')
  await page.locator('#contact-name').fill('Josue')
  await page.locator('#contact-email').fill('josue@example.com')
  await page.locator('#contact-message').fill('Test message')
  await page.locator('.contact-form button').click()
  await expect(page.locator('.contact-form__status')).toContainText('received your message')
  await page.locator('#newsletter-email').fill('josue@example.com')
  await page.locator('.newsletter button').click()
  await expect(page.locator('#newsletter-status')).toContainText('Thank')
  await openSignup(page)
  await page.locator('[data-switch]').click()
  await page.locator('#login-email').fill('josue@example.com')
  await page.locator('#login-password').fill('test1234')
  await page.locator('dialog [type="submit"]').click()
  await expect(page.locator('.login-form__status')).toContainText('try again')
  await expect(page.locator('dialog')).toBeVisible()
  await page.locator('[data-switch]').click()
  await page.locator('#signup-name').fill('Josue')
  await page.locator('#signup-email').fill('josue@example.com')
  await page.locator('#signup-company').fill('RentBuild')
  await page.locator('#signup-password').fill('test1234')
  await page.locator('dialog [type="submit"]').click()
  await expect(page.locator('.dashboard-shell')).toBeVisible()
  expect(requests).toHaveLength(4)
  expect(requests[0].body).toEqual({ name: 'Josue', email: 'josue@example.com', message: 'Test message' })
  expect(requests[3].body.plan).toBeTruthy()
  expect(requests[3].body.period).toBe('annual')
})
