import { test, expect } from '@playwright/test'

async function openSignup(page) {
  await page.locator('.pricing-card .btn').first().click()
  await expect(page.locator('dialog')).toBeVisible()
}
async function signup(page, name = 'Josue Test') {
  await openSignup(page)
  await page.locator('#signup-name').fill(name)
  await page.locator('#signup-email').fill('josue@example.com')
  await page.locator('#signup-company').fill('RentBuild')
  await page.locator('#signup-password').fill('test1234')
  await page.locator('dialog [type="submit"]').click()
  await expect(page.locator('.dashboard-shell')).toBeVisible()
}

test('production page retains all sections, artwork and external app links', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.locator('main section[id]')).toHaveCount(9)
  await expect(page.locator('h1')).toHaveText('Manage your machinery with total control.')
  await expect(page.locator('.team-card')).toHaveCount(5)
  await expect(page.locator('.navbar__actions a').first()).toHaveAttribute('href', 'https://dataflux-webapp.vercel.app/iam/sign-in')
  await page.locator('img').evaluateAll(images => images.forEach(img => { img.loading = 'eager' }))
  await page.locator('#contact').scrollIntoViewIfNeeded()
  await expect.poll(() => page.locator('img').evaluateAll(images => images.every(img => img.complete && img.naturalWidth > 0))).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(errors).toEqual([])
})

